// lion-hawk test (spec §7.1): node --test over the game's test directory, plus a generated test file running the engine
// checks on the game named by test.game (determinism, materials, sim purity over test.roots; zeroAlloc with
// test.zeroAlloc). Tests named @visual run only with --visual. runTests({ game, visual }) → exit code.
import { spawn } from 'node:child_process';
import { existsSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { loadConfig } from '../bake/config.js';

const CHECKS = pathToFileURL(resolve(new URL('../../testing/checks.js', import.meta.url).pathname)).href;

const checksFile = (cfg, t) => `// generated by lion-hawk test: the engine checks for ${cfg.id}
import test from 'node:test';
import assert from 'node:assert/strict';
import { checks } from ${JSON.stringify(CHECKS)};
import game from ${JSON.stringify(pathToFileURL(resolve(cfg.dir, t.game)).href)};
test('engine checks: determinism', () => { const r = checks.determinism(game); assert.ok(r.ok, \`checksums differ at step \${r.step}\`); });
test('engine checks: materials', () => { const r = checks.materials(game); assert.ok(r.ok, JSON.stringify({ missing: r.missing, hash: r.hash })); });
${t.roots ? `test('engine checks: sim purity', () => { const r = checks.simPurity(game, { roots: ${JSON.stringify(t.roots.map(p => resolve(cfg.dir, p)))} }); assert.ok(r.ok, JSON.stringify(r.found)); });\n` : ''}${t.zeroAlloc ? `test('engine checks: zero allocation', () => { const r = checks.zeroAlloc(game); assert.ok(r.ok, \`retained growth \${r.growth} bytes\`); });\n` : ''}`;

export async function runTests({ game = '.', visual = false, log = console.log } = {}) {
  const cfg = typeof game === 'string' ? await loadConfig(game) : game, t = cfg.test;
  const files = [], dir = resolve(cfg.dir, t.dir);
  if (existsSync(dir)) files.push(dir);
  let tmp = null;
  if (t.game) { tmp = mkdtempSync(join(tmpdir(), 'lh-checks-')); const f = join(tmp, 'engine-checks.test.mjs'); writeFileSync(f, checksFile(cfg, t)); files.push(f); }
  if (!files.length) throw new Error('test: nothing to run (no test/ directory and no test.game)');
  const args = ['--test', ...(visual ? [] : ['--test-skip-pattern=@visual']), ...files];
  log(`test: ${cfg.id} ${visual ? '(with @visual)' : '(@visual skipped)'}`);
  try {
    const env = { ...process.env, LH_VISUAL: visual ? '1' : '' }; delete env.NODE_TEST_CONTEXT;
    return await new Promise((ok, fail) => spawn(process.execPath, args, { cwd: cfg.dir, stdio: 'inherit', env }).on('error', fail).on('exit', code => ok(code ?? 1)));
  } finally { if (tmp) rmSync(tmp, { recursive: true, force: true }); }
}
