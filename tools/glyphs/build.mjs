// Regenerates src/kits/glyphs/icons.js (U-10) from Kenney's Input Prompts (CC0), the Vector set of the All-in-1 pack:
//   node tools/glyphs/build.mjs "<...>/Kenney Game Assets All-in-1 3.7.0/Icons/Input Prompts"
// One SVG per role and family; a role a family has no input for is left out (its glyph hides).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const SOURCES = {
  xbox:    ['Xbox Series', { confirm: 'xbox_button_a', back: 'xbox_button_b', menu: 'xbox_button_menu', move: 'xbox_dpad', prev: 'xbox_lb', next: 'xbox_rb', view: 'xbox_button_view' }],
  ps:      ['PlayStation Series', { confirm: 'playstation_button_cross', back: 'playstation_button_circle', menu: 'playstation5_button_options', move: 'playstation_dpad', prev: 'playstation_trigger_l1', next: 'playstation_trigger_r1', view: 'playstation5_button_create' }],
  deck:    ['Steam Deck', { confirm: 'steamdeck_button_a', back: 'steamdeck_button_b', menu: 'steamdeck_button_options', move: 'steamdeck_dpad', prev: 'steamdeck_button_l1', next: 'steamdeck_button_r1', view: 'steamdeck_button_view' }],
  generic: ['Generic', { confirm: 'generic_button', back: 'generic_button_circle', menu: 'generic_button_square', move: 'generic_stick', prev: 'generic_button_trigger_a', next: 'generic_button_trigger_b', view: 'generic_button_square_outline' }],
  keys:    ['Keyboard & Mouse', { confirm: 'keyboard_enter', back: 'keyboard_escape', menu: 'keyboard_escape', move: 'keyboard_arrows_all' }],
  pointer: ['Keyboard & Mouse', { confirm: 'mouse_left' }],
  touch:   ['Touch', { confirm: 'touch_tap' }],
};

const root = process.argv[2];
if (!root) { console.error('usage: node tools/glyphs/build.mjs "<Kenney Input Prompts dir>"'); process.exit(1); }
const out = {};
for (const [family, [dir, roles]] of Object.entries(SOURCES)) {
  out[family] = {};
  for (const [role, file] of Object.entries(roles)) {
    const svg = fs.readFileSync(path.join(root, dir, 'Vector', `${file}.svg`), 'utf8');
    out[family][role] = svg.replace(/<defs\/>/g, '').replace(/>\s+</g, '><').trim(); // whitespace between tags only
  }
}
const here = path.dirname(fileURLToPath(import.meta.url)), dest = path.join(here, '../../src/kits/glyphs/icons.js');
const body = `// Generated by tools/glyphs/build.mjs from Kenney Input Prompts 1.5A (CC0, www.kenney.nl; see LICENSE.txt). Do not edit.\n` +
  `export const ICONS = ${JSON.stringify(out, null, 1)};\n`;
fs.writeFileSync(dest, body);
fs.copyFileSync(path.join(root, 'License.txt'), path.join(here, '../../src/kits/glyphs/LICENSE.txt'));
console.log(`wrote ${path.relative(process.cwd(), dest)} (${body.length} bytes)`);
